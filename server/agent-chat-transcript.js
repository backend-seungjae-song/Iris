// 에이전트 대화 기록(Claude Code transcript · Codex rollout)을 채팅 메시지 목록으로 바꾸는 순수 부분.
//
// 소유 범위
//   한 줄 해석(decodeClaudeLine · decodeCodexLine), 하네스가 끼워 넣은 턴 판정(isNoiseMessage),
//   바이트 위치를 기억하며 파일 끝에서 거꾸로 읽기(readTailWindow)와 이어 읽기(readForward).
//
// 제공 API
//   decodeLine(kind, line, fallbackId) · isNoiseMessage(msg) · readTailWindow(source, opts) ·
//   readForward(source, from, kind) · LIMITS.
//
// 의존 대상
//   아무것도 import 하지 않는다. 파일은 source({ size, readAt(buf, pos) }) 로만 받으므로 검사가
//   Buffer 로 같은 함수를 부른다.
//
// 유지 조건
//   transcript 는 이 서버가 보증하지 않는 입력이다. 줄이 깨졌거나 모르는 형태면 버리고 예외를 내지
//   않는다. 도구 입력·결과는 여기서 잘라 보낸다(한 줄이 수 MB 인 도구 결과가 있다).
//   Codex 는 같은 말을 response_item.message 와 event_msg(user_message·agent_message) 두 곳에
//   적는 판(0.13x)이 있고 뒤 판(0.155)은 response_item 만 적는다(실제 rollout 로 확인). 그래서
//   response_item 만 읽고 event_msg 는 turn_aborted 만 쓴다.
//
// 영향 범위
//   server/agent-chat.js 와 test/agent-chat.mjs. 현재 목록 확인: node bin/importers.mjs server/agent-chat-transcript.js

export const LIMITS = {
  chunk: 64 * 1024,
  initial: 300,
  older: 200,
  append: 400,
  toolResult: 4000,
  inputString: 8000,
  text: 60000,
};

// Claude Code 가 사용자 턴처럼 적지만 사람이 쓴 것이 아닌 것들. 앞머리 태그로 판정한다.
const HARNESS_TAGS = new Set([
  "agent-message", "bash-stderr", "bash-stdout", "command-args", "command-message", "command-name",
  "cross-session-message", "fork-boilerplate", "local-command-caveat", "local-command-stderr",
  "local-command-stdout", "mcp-polling-update", "mcp-resource-update", "system-reminder",
  "task-notification", "teammate-message", "user-memory-input", "user-prompt-submit-hook",
  // Codex 가 사용자 역할로 끼워 넣는 문맥
  "environment_context", "user_instructions", "recommended_plugins", "skill", "turn_aborted",
  "model_switch", "permissions",
]);
const HARNESS_PREFIXES = [
  "<channel source=", "[request interrupted", "a message arrived from ",
  "another claude session sent a message", "no response requested.",
  "caveat: the messages below were generated by the user while running local commands",
  "this session is being continued from a previous conversation",
  "# agents.md instructions",
];

function messageText(msg) {
  return msg.blocks.filter((b) => b.type === "text").map((b) => b.text).join("").trim();
}

export function isNoiseMessage(msg) {
  if (!msg || (msg.role !== "user" && msg.role !== "system")) return false;
  if (msg.blocks.some((b) => b.type === "tool-call" || b.type === "tool-result")) return false;
  const head = messageText(msg).slice(0, 256).toLowerCase();
  if (!head) return true;
  const tag = /^<([a-z][a-z0-9_-]*)(?:[\s>]|$)/.exec(head)?.[1];
  if (tag && HARNESS_TAGS.has(tag)) return true;
  return HARNESS_PREFIXES.some((p) => head.startsWith(p));
}

const clip = (s, n) => (s.length > n ? `${s.slice(0, n)}…` : s);

// 도구 입력의 긴 문자열만 자른다. 구조는 남겨 두어야 화면이 파일 경로·diff 를 만든다.
function boundInput(value, depth = 0) {
  if (typeof value === "string") return clip(value, LIMITS.inputString);
  if (!value || typeof value !== "object" || depth > 4) return value ?? null;
  if (Array.isArray(value)) return value.slice(0, 50).map((v) => boundInput(v, depth + 1));
  const out = {};
  for (const [k, v] of Object.entries(value).slice(0, 50)) out[k] = boundInput(v, depth + 1);
  return out;
}

function resultText(content) {
  if (typeof content === "string") return content;
  if (Array.isArray(content)) {
    return content.map((c) => {
      if (typeof c === "string") return c;
      if (c && typeof c.text === "string") return c.text;
      if (c && (c.type === "image" || c.type === "input_image")) return "[이미지]";
      return "";
    }).filter(Boolean).join("\n");
  }
  if (content && typeof content === "object") {
    if (typeof content.output === "string") return content.output;
    if (typeof content.content === "string") return content.content;
    try { return JSON.stringify(content); } catch { return ""; }
  }
  return content == null ? "" : String(content);
}

function ts(value) {
  const n = typeof value === "number" ? value : Date.parse(value);
  return Number.isFinite(n) ? n : null;
}

function parse(line) {
  try {
    const r = JSON.parse(line);
    return r && typeof r === "object" ? r : null;
  } catch { return null; }
}

// ── Claude Code ─────────────────────────────────────────────────────────────
// 한 줄 = assistant 블록 하나 또는 user 턴 하나. thinking 은 흐린 줄로 따로 떼고, tool_result 만
// 담긴 user 줄은 도구 결과 메시지(role tool)가 된다.
function decodeClaude(rec, fallbackId) {
  if (rec.type !== "user" && rec.type !== "assistant") return [];
  const id = typeof rec.uuid === "string" ? rec.uuid : fallbackId;
  const time = ts(rec.timestamp);
  const content = rec.message?.content;
  const machine = !!(rec.isMeta || rec.isSynthetic || rec.isCompactSummary);
  if (typeof content === "string") {
    if (machine || rec.type !== "user") return rec.type === "assistant" && content ? [{ id, role: "assistant", blocks: [{ type: "text", text: clip(content, LIMITS.text) }], ts: time }] : [];
    return [{ id, role: "user", blocks: [{ type: "text", text: clip(content, LIMITS.text) }], ts: time }];
  }
  if (!Array.isArray(content)) return [];
  const out = [];
  const main = [];
  const results = [];
  for (const c of content) {
    if (!c || typeof c !== "object") continue;
    if (c.type === "text" && typeof c.text === "string" && c.text) { if (!machine) main.push({ type: "text", text: clip(c.text, LIMITS.text) }); }
    else if (c.type === "thinking" && typeof c.thinking === "string" && c.thinking.trim()) {
      out.push({ id: `${id}:r${out.length}`, role: "reasoning", blocks: [{ type: "text", text: clip(c.thinking, LIMITS.text) }], ts: time });
    } else if (c.type === "tool_use") {
      main.push({ type: "tool-call", id: typeof c.id === "string" ? c.id : null, name: String(c.name || "tool"), input: boundInput(c.input) });
    } else if (c.type === "tool_result") {
      results.push({ type: "tool-result", id: typeof c.tool_use_id === "string" ? c.tool_use_id : null, output: clip(resultText(c.content), LIMITS.toolResult), isError: c.is_error === true });
    } else if (c.type === "image" && !machine) main.push({ type: "image" });
  }
  if (main.length) out.push({ id, role: rec.type === "assistant" ? "assistant" : "user", blocks: main, ts: time });
  if (results.length) out.push({ id: `${id}:t`, role: "tool", blocks: results, ts: time });
  return out;
}

// ── Codex rollout ───────────────────────────────────────────────────────────
function codexContentBlocks(content) {
  if (typeof content === "string") return content ? [{ type: "text", text: clip(content, LIMITS.text) }] : [];
  if (!Array.isArray(content)) return [];
  const blocks = [];
  for (const c of content) {
    if (!c || typeof c !== "object") continue;
    if (typeof c.text === "string" && c.text && /text$/.test(String(c.type || "text"))) blocks.push({ type: "text", text: clip(c.text, LIMITS.text) });
    else if (c.type === "input_image" || c.type === "image") blocks.push({ type: "image" });
  }
  return blocks;
}

function codexArgs(payload) {
  const raw = payload.arguments ?? payload.input ?? payload.action ?? null;
  if (typeof raw === "string" && payload.arguments !== undefined) {
    const parsed = parse(raw);
    if (parsed) return boundInput(parsed);
  }
  return boundInput(raw);
}

function decodeCodex(rec, fallbackId) {
  const p = rec.payload;
  if (!p || typeof p !== "object") return [];
  const id = typeof p.id === "string" ? p.id : fallbackId;
  const time = ts(rec.timestamp);
  if (rec.type === "event_msg") {
    return p.type === "turn_aborted" ? [{ id, role: "system", blocks: [{ type: "text", text: "중단됨" }], ts: time }] : [];
  }
  if (rec.type !== "response_item") return [];
  if (p.type === "message") {
    if (p.role !== "user" && p.role !== "assistant" && p.role !== "system") return [];
    const blocks = codexContentBlocks(p.content);
    return blocks.length ? [{ id, role: p.role, blocks, ts: time }] : [];
  }
  if (p.type === "reasoning") {
    const parts = [];
    if (typeof p.text === "string") parts.push(p.text);
    for (const s of Array.isArray(p.summary) ? p.summary : []) if (typeof s?.text === "string") parts.push(s.text);
    for (const s of Array.isArray(p.content) ? p.content : []) if (typeof s?.text === "string") parts.push(s.text);
    const text = parts.join("\n").trim();
    return text ? [{ id, role: "reasoning", blocks: [{ type: "text", text: clip(text, LIMITS.text) }], ts: time }] : [];
  }
  if (p.type === "function_call" || p.type === "custom_tool_call" || p.type === "local_shell_call") {
    const name = String(p.name || (p.type === "local_shell_call" ? "shell" : "tool"));
    return [{ id, role: "assistant", blocks: [{ type: "tool-call", id: typeof p.call_id === "string" ? p.call_id : null, name, input: codexArgs(p) }], ts: time }];
  }
  if (p.type === "function_call_output" || p.type === "custom_tool_call_output" || p.type === "local_shell_call_output") {
    const o = p.output;
    const isError = !!(o && typeof o === "object" && !Array.isArray(o) && (o.success === false || o.is_error === true));
    return [{ id, role: "tool", blocks: [{ type: "tool-result", id: typeof p.call_id === "string" ? p.call_id : null, output: clip(resultText(o), LIMITS.toolResult), isError }], ts: time }];
  }
  return [];
}

export function decodeLine(kind, line, fallbackId) {
  if (!line || line.length < 2) return [];
  const rec = parse(line);
  if (!rec) return [];
  const out = kind === "codex" ? decodeCodex(rec, fallbackId) : decodeClaude(rec, fallbackId);
  return out.filter((m) => !isNoiseMessage(m));
}

// ── 바이트 위치 읽기 ─────────────────────────────────────────────────────────
// source: { size, readAt(buf, pos) → 읽은 바이트 수 }. 줄 경계는 바이트 10 으로 나눈다. UTF-8 에서
// 10 은 다른 글자의 일부가 되지 않으므로 글자를 중간에서 자르지 않는다.
function decodeRange(kind, buf, base) {
  const entries = [];
  let at = 0;
  while (at < buf.length) {
    const nl = buf.indexOf(10, at);
    const end = nl < 0 ? buf.length : nl;
    const off = base + at;
    const msgs = decodeLine(kind, buf.subarray(at, end).toString("utf8"), `L${off}`);
    if (msgs.length) entries.push({ off, msgs });
    at = end + 1;
  }
  return entries;
}

// [stopAt, end) 구간을 파일 끝 쪽부터 거꾸로 읽어 메시지 want 개를 모은다. end 는 줄 경계여야 한다.
// 돌려주는 start 는 포함한 첫 줄의 시작 위치다. 다음 "이전 더 읽기"가 거기서 이어진다.
export function readTailWindow(source, { end, stopAt = 0, want, kind }) {
  let pos = end;
  let carry = Buffer.alloc(0);
  let entries = [];
  let count = 0;
  let exhausted = false;
  while (count < want) {
    if (pos <= stopAt) { exhausted = true; break; }
    const n = Math.min(LIMITS.chunk, pos - stopAt);
    pos -= n;
    const chunk = Buffer.alloc(n);
    if (source.readAt(chunk, pos) < n) { exhausted = true; break; }   // 그사이 파일이 줄었다
    const buf = Buffer.concat([chunk, carry]);
    // 아직 앞이 남았으면 첫 조각은 줄 중간일 수 있으므로 다음 회차로 넘긴다.
    const cut = pos > stopAt ? buf.indexOf(10) + 1 : 0;
    if (pos > stopAt && cut === 0) { carry = buf; continue; }
    const fresh = decodeRange(kind, buf.subarray(cut), pos + cut);
    entries = fresh.concat(entries);
    for (const e of fresh) count += e.msgs.length;
    carry = buf.subarray(0, cut);
  }
  // 넘치게 읽은 앞쪽 줄은 버린다. 버린 줄은 다음 "이전 더 읽기"가 다시 읽는다.
  let trimmed = false;
  while (entries.length > 1 && count - entries[0].msgs.length >= want) {
    count -= entries[0].msgs.length;
    entries.shift();
    trimmed = true;
  }
  const start = exhausted && !trimmed ? stopAt : (entries.length ? entries[0].off : pos);
  return { messages: entries.flatMap((e) => e.msgs), start, hasOlder: start > stopAt };
}

// from 부터 파일 끝까지. 마지막 줄이 아직 쓰이는 중(\n 없음)이면 그 줄은 다음 회차로 미룬다.
export function readForward(source, from, kind) {
  const size = source.size;
  if (size <= from) return { messages: [], end: from };
  const buf = Buffer.alloc(size - from);
  const got = source.readAt(buf, from);
  const view = buf.subarray(0, got);
  const last = view.lastIndexOf(10);
  if (last < 0) return { messages: [], end: from };
  const entries = decodeRange(kind, view.subarray(0, last), from);
  return { messages: entries.flatMap((e) => e.msgs), end: from + last + 1 };
}

// 파일 크기에서 마지막 완성 줄의 끝. 쓰이는 중인 마지막 줄을 첫 창에 넣지 않는다.
export function completeEnd(source) {
  const size = source.size;
  if (!size) return 0;
  const probe = Math.min(size, LIMITS.chunk);
  let pos = size;
  while (pos > 0) {
    const n = Math.min(probe, pos);
    const buf = Buffer.alloc(n);
    source.readAt(buf, pos - n);
    const i = buf.lastIndexOf(10);
    if (i >= 0) return pos - n + i + 1;
    pos -= n;
  }
  return 0;
}

/* 용어. 이 판에서 쓰는 이름의 정본.

   소유 범위
     용어 하나와 그 뜻, 그리고 툴팁이 가져갈 문구.

   제공 API
     TERMS · TERM_OF · tip(word).

   의존 대상
     없다. 데이터 하나다.

   유지 조건
     같은 것을 두 이름으로 부르면 그때부터 다른 두 가지가 된다. 용어 화면도 툴팁도 여기서만
     가져간다. 두 곳에 각각 적으면 한쪽만 고쳐져 화면이 서로 다른 용어를 쓰게 된다.

   영향 범위
     app.js 의 툴팁과 말뜻 화면.
*/

/* 한 단어가 여러 뜻으로 쓰이면 화면과 툴팁이 서로 다른 것을 가리키므로, 용어는 여기서
   하나의 뜻으로만 정의한다.

   낱말 데이터: 여기 값은 화면 문구가 아니라 뜻풀이라서 라벨체 검사가 건너뛴다. */
export const TERMS = [
  ['판', '메모 한 벌', '왼쪽 줄에서 고르기. 보관함도 판 하나.'],
  ['조각', '적은 한 장', '누르면 고치기, 끌면 옮기기.'],
  ['분류', '탭 하나', '칸 분류와 그림 분류 둘.'],
  ['칸 분류', '칸이 있는 분류', '묶음 · 나눔 · 할 일 · 회의 · 공부 · 준비 · 흐름'],
  ['그림 분류', '칸이 없는 분류', '갈래 · 이음 · 마인드맵. 선과 자리가 뜻.'],
  ['칸', '조각이 들어가는 곳', '공부면 그대로 · 내 말로 · 의문 · 그래서 나는'],
  ['더미', '어느 칸에도 안 넣은 조각', '안 넣어도 기록은 기록. 분류마다 따로 세기.'],
  ['위치', '공부에서 조각에 찍는 자리 표시', '2-2 · 3-5 처럼. 강의 시각이나 쪽 번호.'],
  ['덩어리', '묶음 분류 안의 한 묶음', '이름은 사람이 정하기.'],
  ['줄', '흐름의 가로줄', '우리 쪽 · 고객 쪽처럼 나란히 갈 때.'],
  ['단계', '흐름의 세로 칸', '신청 → 심사 → 발송'],
  ['놓은 곳', '마인드맵에서 끌어다 둔 자리', '한 번 옮긴 곳은 계산 밖.'],
  ['보관함', '판에 넣기 전에 던져 두는 판', '어느 판으로 보낼지는 나중에.'],
];

// 한 줄에 한 사실. 이어 붙이면 툴팁 안에서 다시 문장이 된다
export const TERM_OF = Object.fromEntries(TERMS.map(([w, d, more]) => [w, `${w}\n${d}\n${more}`]));
// 툴팁은 이 함수로만 붙인다. 직접 적으면 이 표와 일치하지 않게 된다
export const tip = (w) => TERM_OF[w] || w;
